    <h1>Conditions générales de vente et d'utilisation</h1>

    <h2>1. Objet</h2>
    <p>Les présentes conditions régissent la location de studios de tournage et de matériel proposée par Setly, loueur unique.</p>

    <h2>2. Réservation</h2>
    <p>La réservation s'effectue en ligne par un client disposant d'un compte. Le prix est calculé au moment de la validation : tarif horaire du studio multiplié par la durée réservée, auquel s'ajoutent le matériel optionnel et, le cas échéant, les frais de livraison.</p>

    <h2>3. Tarifs et réductions</h2>
    <p>Une réduction de <strong>10 %</strong> est appliquée sur le prix du studio pour toute réservation d'une journée complète (8 heures ou plus). Les frais de livraison du matériel s'élèvent à <strong>5,00 € plus 0,59 € par kilomètre</strong> hors Paris ; le retrait sur place est gratuit.</p>

    <h2>4. Statuts et suivi</h2>
    <p>Chaque réservation suit les statuts : en attente, confirmée, en préparation, en cours, puis terminée. Le client peut modifier ou annuler sa réservation tant qu'elle est « en attente ». Une fois confirmée, il accède au suivi en temps réel.</p>

    <h2>5. Retour du matériel</h2>
    <p>Lorsque du matériel a été loué, la réservation passe en « attente du retour de matériel » après la prestation. Le matériel doit être restitué sous <strong>10 jours ouvrés</strong>. À défaut, des frais forfaitaires de <strong>600 €</strong> sont appliqués.</p>

    <h2>6. Avis</h2>
    <p>Après une prestation terminée, le client peut déposer un avis (note et commentaire). Les avis sont publiés après modération par notre équipe.</p>

    <h2>7. Données personnelles</h2>
    <p>Voir les mentions légales pour le traitement des données conformément au RGPD.</p>
